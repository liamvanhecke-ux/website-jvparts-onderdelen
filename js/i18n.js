function detecteerTaal() {
    const opgeslagen = localStorage.getItem(I18N_KEY);
    if (opgeslagen && TALEN.includes(opgeslagen)) return opgeslagen;
    const browserTaal = (navigator.language || navigator.userLanguage || 'nl').slice(0, 2).toLowerCase();
    return TALEN.includes(browserTaal) ? browserTaal : 'nl';
}

let huidigeTaal = detecteerTaal();

function t(key, vars) {
    let tekst = (VERTALINGEN[huidigeTaal] && VERTALINGEN[huidigeTaal][key])
        || (VERTALINGEN.nl && VERTALINGEN.nl[key])
        || key;
    if (vars) {
        Object.keys(vars).forEach(k => {
            tekst = tekst.replace('{' + k + '}', vars[k]);
        });
    }
    return tekst;
}

function pasVertalingenToe() {
    document.documentElement.lang = huidigeTaal;

    document.querySelectorAll('[data-i18n]').forEach(el => {
        el.textContent = t(el.getAttribute('data-i18n'));
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
    });
    document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
        el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria-label')));
    });
    document.querySelectorAll('.taal-knop').forEach(btn => {
        btn.classList.toggle('actief', btn.dataset.taal === huidigeTaal);
    });
}

function stelTaalIn(taal) {
    if (!TALEN.includes(taal) || taal === huidigeTaal) return;
    huidigeTaal = taal;
    localStorage.setItem(I18N_KEY, taal);
    pasVertalingenToe();
    document.dispatchEvent(new CustomEvent('taalGewijzigd', { detail: taal }));
}

function bindTaalKnoppen() {
    document.querySelectorAll('.taal-knop').forEach(btn => {
        btn.addEventListener('click', () => stelTaalIn(btn.dataset.taal));
    });
}

